export const applyReportTemplateVariables = (
  value: string | null | undefined,
  context: ReportTemplatePreviewContext,
) => {
  const template = value || "";
  const replacements: Record<string, string> = {
    "{patient_name}": context.patient_name,
    "{patient_id}": context.patient_id,
    "{phone}": context.phone,
    "{test_name}": context.test_name,
    "{test_date}": context.test_date,
    "{report_date}": context.report_date,
    "{lab_name}": context.lab_name,
    "{lab_code}": context.lab_code,
    "{collection_center}": context.collection_center,
    "{entered_by}": context.entered_by,
  };

  return Object.entries(replacements).reduce(
    (result, [token, replacement]) => result.replaceAll(token, replacement || ""),
    template,
  );
};

export const renderReportTemplateText = (
  value: string | null | undefined,
  context: ReportTemplatePreviewContext,
) =>
  applyReportTemplateVariables(value, context)
    .replace(/<br\s*\/?>/gi, "\n")
    .replace(/<\/p>/gi, "\n")
    .replace(/<li>/gi, "• ")
    .replace(/<\/li>/gi, "\n")
    .replace(/&nbsp;/gi, " ")
    .replace(/<[^>]*>/g, "")
    .replace(/\n{3,}/g, "\n\n")
    .trim();

export const getTemplateScopeLabel = (testCategory?: string | null, testName?: string | null) => {
  if (testName) {
    return `Specific test: ${testName}`;
  }

  if (testCategory) {
    return `Category: ${testCategory}`;
  }

  return "All tests";
};
