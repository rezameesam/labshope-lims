const SHAPE = /^[a-z][a-z0-9-]*[a-z0-9]$/;

/** Why this lab name can't be used, or null when it is fine. */
export const slugProblem = (slug: string | null | undefined): string | null => {
  const value = String(slug || "").trim().toLowerCase();
  if (value.length < MIN_SLUG_LENGTH) return `Lab names need at least ${MIN_SLUG_LENGTH} characters.`;
  if (!SHAPE.test(value)) return "Use letters, digits and hyphens only, starting with a letter.";
  if (RESERVED_SLUGS.has(value)) return "That name is reserved. Please choose a different one.";
  return null;
};

export const isReservedSlug = (slug: string | null | undefined) => slugProblem(slug) !== null;
