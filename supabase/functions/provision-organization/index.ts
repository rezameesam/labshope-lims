import { serve } from "https://deno.land/std@0.190.0/http/server.ts";
import { createClient } from "https://esm.sh/@supabase/supabase-js@2";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type, x-internal-service-key",
  "Access-Control-Allow-Methods": "POST, OPTIONS",
};

interface ProvisionOrganizationRequest {
  slug?: string;
  display_name: string;
  legal_name?: string | null;
  plan_code?: string | null;
  primary_email?: string | null;
  primary_phone?: string | null;
  billing_email?: string | null;
  timezone?: string | null;
  currency_code?: string | null;
  country_code?: string | null;
  primary_domain?: string | null;
  secondary_domain?: string | null;
  owner_email: string;
  owner_password: string;
  owner_full_name: string;
  owner_phone?: string | null;
  owner_designation?: string | null;
  owner_department?: string | null;
  primary_lab_name?: string | null;
  primary_lab_code?: string | null;
}

const OWNER_ORG_ROLE = "owner";
const DEFAULT_OWNER_DESIGNATION = "Administrator";
const DEFAULT_OWNER_DEPARTMENT = "Administration";
const DEFAULT_PLAN_CODE = "standard";
const DEFAULT_TIMEZONE = "Asia/Kolkata";
const DEFAULT_CURRENCY = "INR";
const DEFAULT_COUNTRY = "IN";
const DEFAULT_BRANDING_TAGLINE = "Modern diagnostics, delivered with clarity.";
const DEFAULT_REPORT_TAGLINE = "Accurate diagnostic reporting for better clinical decisions.";
const DEFAULT_REPORT_FOOTER_NOTE = "This is a computer-generated report and does not require a physical signature.";
const DEFAULT_TEMPLATE_NAME = "Standard Report Template";
const DEFAULT_TEMPLATE_HEADER =
  "<p><strong>Patient:</strong> {patient_name} ({patient_id})</p><p><strong>Collected:</strong> {test_date} | <strong>Report:</strong> {report_date}</p>";
const DEFAULT_TEMPLATE_FOOTER =
  "<p>Processed at {lab_name} {lab_code}</p><p>Generated by {entered_by}</p>";
const SLUG_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const LAB_CODE_PATTERN = /^[A-Z0-9-]{3,20}$/;

const jsonResponse = (payload: Record<string, unknown>, status: number) =>
  new Response(JSON.stringify(payload), {
    status,
    headers: { ...corsHeaders, "Content-Type": "application/json" },
  });

const slugify = (value: string) =>
  value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .replace(/-{2,}/g, "-");

const normalizeDomain = (value: string | null | undefined): string | null => {
  const trimmed = value?.trim().toLowerCase();
  if (!trimmed) {
    return null;
  }

  try {
    return new URL(trimmed).hostname.toLowerCase();
  } catch {
    return trimmed.replace(/:\d+$/, "");
  }
};

const generateEmployeeId = () =>
  `ADM${crypto.randomUUID().replace(/-/g, "").slice(0, 8).toUpperCase()}`;

const PLAN_CODE_TO_TIER: Record<string, string> = {
  starter: "starter",
  growth: "growth",
  premium: "premium",
  standard: "starter", // legacy default
  basic: "starter",
  pro: "growth",
  enterprise: "premium",
};

const buildOrganizationSettingsPayload = ({
  organizationId,
  websiteValue,
  planTier,
}: {
  organizationId: string;
  websiteValue: string | null;
  planTier: string;
}) => {
  const settings = [
    {
      organization_id: organizationId,
      setting_key: "plan_tier",
      setting_value: planTier,
      setting_type: "text",
      category: "general",
      label: "Plan Tier",
      description: "Current subscription plan tier for this organization.",
      is_encrypted: false,
    },
    {
      organization_id: organizationId,
      setting_key: "branding_tagline",
      setting_value: DEFAULT_BRANDING_TAGLINE,
      setting_type: "text",
      category: "general",
      label: "Brand Tagline",
      description: "Short public-facing tagline used across the site and reports.",
      is_encrypted: false,
    },
    {
      organization_id: organizationId,
      setting_key: "report_tagline",
      setting_value: DEFAULT_REPORT_TAGLINE,
      setting_type: "text",
      category: "general",
      label: "Report Tagline",
      description: "Short supporting line shown on generated reports.",
      is_encrypted: false,
    },
    {
      organization_id: organizationId,
      setting_key: "report_footer_note",
      setting_value: DEFAULT_REPORT_FOOTER_NOTE,
      setting_type: "text",
      category: "general",
      label: "Report Footer Note",
      description: "Default note shown at the bottom of generated reports.",
      is_encrypted: false,
    },
    {
      organization_id: organizationId,
      setting_key: "report_default_header_template",
      setting_value: DEFAULT_TEMPLATE_HEADER,
      setting_type: "text",
      category: "general",
      label: "Default Report Header Template",
      description: "Starter header template for new report formats.",
      is_encrypted: false,
    },
    {
      organization_id: organizationId,
      setting_key: "report_default_footer_template",
      setting_value: DEFAULT_TEMPLATE_FOOTER,
      setting_type: "text",
      category: "general",
      label: "Default Report Footer Template",
      description: "Starter footer template for new report formats.",
      is_encrypted: false,
    },
  ];

  if (websiteValue) {
    settings.push({
      organization_id: organizationId,
      setting_key: "organization_website",
      setting_value: websiteValue,
      setting_type: "text",
      category: "other",
      label: "Organization Website",
      description: "Primary website URL for public branding and links.",
      is_encrypted: false,
    });
  }

  return settings;
};

serve(async (req: Request) => {
  if (req.method === "OPTIONS") {
    return new Response("ok", { headers: corsHeaders });
  }

  try {
    const supabaseUrl = Deno.env.get("SUPABASE_URL") || "";
    const serviceRoleKey = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY") || "";
    const secretKey = Deno.env.get("SUPABASE_SECRET_KEY") || "";
    const internalServiceKey = req.headers.get("x-internal-service-key")?.trim() || "";
    const apiKeyHeader = req.headers.get("apikey")?.trim() || "";
    const authorizationHeader = req.headers.get("Authorization")?.trim() || "";
    const bearerToken = authorizationHeader.toLowerCase().startsWith("bearer ")
      ? authorizationHeader.slice(7).trim()
      : "";

    if (!supabaseUrl || !serviceRoleKey) {
      return jsonResponse({ error: "Server configuration missing." }, 500);
    }

    const acceptedInternalKeys = new Set(
      [serviceRoleKey, secretKey].map((value) => value.trim()).filter(Boolean),
    );

    const presentedKeys = [internalServiceKey, apiKeyHeader, bearerToken].filter(Boolean);

    if (presentedKeys.length === 0 || !presentedKeys.some((value) => acceptedInternalKeys.has(value))) {
      return jsonResponse({ error: "Unauthorized" }, 401);
    }

    const payload: ProvisionOrganizationRequest = await req.json();
    const displayName = payload.display_name?.trim();
    const ownerEmail = payload.owner_email?.trim().toLowerCase();
    const ownerPassword = payload.owner_password?.trim();
    const ownerFullName = payload.owner_full_name?.trim();
    const slug = slugify(payload.slug || displayName || "");
    const labName = payload.primary_lab_name?.trim() || `${displayName} Main Lab`;
    const labCode = (payload.primary_lab_code?.trim().toUpperCase() || "LAB001");
    const primaryDomain = normalizeDomain(payload.primary_domain);
    const secondaryDomain = normalizeDomain(payload.secondary_domain);

    if (!displayName || !ownerEmail || !ownerPassword || !ownerFullName) {
      return jsonResponse(
        { error: "display_name, owner_email, owner_password, and owner_full_name are required." },
        400,
      );
    }

    if (!slug || !SLUG_PATTERN.test(slug)) {
      return jsonResponse({ error: "A valid organization slug is required." }, 400);
    }

    if (!LAB_CODE_PATTERN.test(labCode)) {
      return jsonResponse({ error: "primary_lab_code must be 3-20 uppercase letters, numbers, or hyphens." }, 400);
    }

    const supabaseAdmin = createClient(supabaseUrl, serviceRoleKey, {
      auth: { autoRefreshToken: false, persistSession: false },
    });

    const { data: existingOrganization } = await supabaseAdmin
      .from("organizations")
      .select("id")
      .eq("slug", slug)
      .limit(1)
      .maybeSingle();

    if (existingOrganization?.id) {
      return jsonResponse({ error: "An organization with this slug already exists." }, 409);
    }

    if (primaryDomain) {
      const { data: existingDomain } = await supabaseAdmin
        .from("organization_domains")
        .select("id")
        .eq("domain", primaryDomain)
        .limit(1)
        .maybeSingle();

      if (existingDomain?.id) {
        return jsonResponse({ error: "That domain is already attached to another organization." }, 409);
      }
    }

    if (secondaryDomain && secondaryDomain !== primaryDomain) {
      const { data: existingSecondaryDomain } = await supabaseAdmin
        .from("organization_domains")
        .select("id")
        .eq("domain", secondaryDomain)
        .limit(1)
        .maybeSingle();

      if (existingSecondaryDomain?.id) {
        return jsonResponse({ error: "That fallback domain is already attached to another organization." }, 409);
      }
    }

    let organizationId: string | null = null;
    let labId: string | null = null;
    let userId: string | null = null;
    let userWasCreated = false;
    let employeeCreated = false;

    const rollback = async () => {
      // Only clean up records scoped to the new org/lab — never touch other orgs
      if (userId && labId) {
        await supabaseAdmin.from("lab_users").delete().eq("user_id", userId).eq("lab_id", labId);
      }
      if (userId && organizationId) {
        await supabaseAdmin.from("organization_users").delete().eq("user_id", userId).eq("organization_id", organizationId);
        if (employeeCreated) {
          await supabaseAdmin.from("employees").delete().eq("user_id", userId).eq("organization_id", organizationId);
        }
      }
      // Only delete auth user if we created them in this request
      if (userId && userWasCreated) {
        await supabaseAdmin.from("user_roles").delete().eq("user_id", userId);
        await supabaseAdmin.auth.admin.deleteUser(userId);
      }

      if (labId) {
        await supabaseAdmin.from("lab_settings").delete().eq("lab_id", labId);
        await supabaseAdmin.from("labs").delete().eq("id", labId);
      }

      if (organizationId) {
        await supabaseAdmin.from("organization_settings").delete().eq("organization_id", organizationId);
        await supabaseAdmin.from("organization_domains").delete().eq("organization_id", organizationId);
        await supabaseAdmin.from("organization_users").delete().eq("organization_id", organizationId);
        await supabaseAdmin.from("organizations").delete().eq("id", organizationId);
      }
    };

    try {
      const { data: trialSetting } = await supabaseAdmin
        .from("system_settings")
        .select("setting_value")
        .eq("setting_key", "trial_period_days")
        .maybeSingle();
      const trialDays = Math.max(1, parseInt((trialSetting as any)?.setting_value || "14", 10) || 14);

      const { data: insertedOrganization, error: organizationError } = await supabaseAdmin
        .from("organizations")
        .insert({
          slug,
          display_name: displayName,
          legal_name: payload.legal_name?.trim() || null,
          plan_code: payload.plan_code?.trim() || DEFAULT_PLAN_CODE,
          primary_email: payload.primary_email?.trim() || ownerEmail,
          primary_phone: payload.primary_phone?.trim() || null,
          billing_email: payload.billing_email?.trim() || payload.primary_email?.trim() || ownerEmail,
          timezone: payload.timezone?.trim() || DEFAULT_TIMEZONE,
          currency_code: payload.currency_code?.trim().toUpperCase() || DEFAULT_CURRENCY,
          country_code: payload.country_code?.trim().toUpperCase() || DEFAULT_COUNTRY,
          status: "trial",
          trial_ends_at: new Date(Date.now() + trialDays * 24 * 60 * 60 * 1000).toISOString(),
        })
        .select("id")
        .single();

      if (organizationError || !insertedOrganization?.id) {
        throw new Error(`Failed to create organization: ${organizationError?.message || "unknown error"}`);
      }

      organizationId = insertedOrganization.id;

      if (primaryDomain) {
        const { error: domainError } = await supabaseAdmin
          .from("organization_domains")
          .insert({
            organization_id: organizationId,
            domain: primaryDomain,
            is_primary: true,
          });

        if (domainError) {
          throw new Error(`Failed to attach primary domain: ${domainError.message}`);
        }
      }

      if (secondaryDomain && secondaryDomain !== primaryDomain) {
        const { error: secondaryDomainError } = await supabaseAdmin
          .from("organization_domains")
          .insert({
            organization_id: organizationId,
            domain: secondaryDomain,
            is_primary: false,
          });

        if (secondaryDomainError) {
          throw new Error(`Failed to attach fallback domain: ${secondaryDomainError.message}`);
        }
      }

      const { data: insertedLab, error: labError } = await supabaseAdmin
        .from("labs")
        .insert({
          organization_id: organizationId,
          lab_code: labCode,
          name: labName,
          type: "main",
          is_active: true,
          email: payload.primary_email?.trim() || ownerEmail,
          phone: payload.primary_phone?.trim() || null,
        })
        .select("id")
        .single();

      if (labError || !insertedLab?.id) {
        throw new Error(`Failed to create primary lab: ${labError?.message || "unknown error"}`);
      }

      labId = insertedLab.id;

      const { error: labSettingsError } = await supabaseAdmin
        .from("lab_settings")
        .insert({
          lab_id: labId,
        });

      if (labSettingsError) {
        throw new Error(`Failed to create lab settings: ${labSettingsError.message}`);
      }

      const websiteValue = primaryDomain ? `https://${primaryDomain}` : "";
      const rawPlanCode = (payload.plan_code?.trim() || DEFAULT_PLAN_CODE).toLowerCase();
      const planTier = PLAN_CODE_TO_TIER[rawPlanCode] ?? "starter";
      const { error: settingsError } = await supabaseAdmin
        .from("organization_settings")
        .upsert(buildOrganizationSettingsPayload({
          organizationId,
          websiteValue: websiteValue || null,
          planTier,
        }), { onConflict: "organization_id,setting_key" });

      if (settingsError) {
        throw new Error(`Failed to seed organization settings: ${settingsError.message}`);
      }

      const { error: templateError } = await supabaseAdmin
        .from("test_templates")
        .insert({
          organization_id: organizationId,
          name: DEFAULT_TEMPLATE_NAME,
          result_format: "table",
          include_normal_range: true,
          include_abnormal_flag: true,
          include_notes: false,
          header_template: DEFAULT_TEMPLATE_HEADER,
          footer_template: DEFAULT_TEMPLATE_FOOTER,
          is_default: true,
        });

      if (templateError) {
        throw new Error(`Failed to seed default report template: ${templateError.message}`);
      }

      let authUserId: string | null = null;

      const { data: authData, error: authError } = await supabaseAdmin.auth.admin.createUser({
        email: ownerEmail,
        password: ownerPassword,
        email_confirm: true,
        user_metadata: {
          organization_slug: slug,
          organization_id: organizationId,
          role: OWNER_ORG_ROLE,
          must_change_password: true,
          first_login_flow: "self_serve_owner",
        },
      });

      if (authError) {
        const isAlreadyRegistered =
          authError.message?.toLowerCase().includes("already registered") ||
          authError.message?.toLowerCase().includes("already been registered");

        if (!isAlreadyRegistered) {
          throw new Error(`Failed to create owner auth user: ${authError.message}`);
        }

        // User already exists — look them up and update their password
        const searchRes = await fetch(
          `${supabaseUrl}/auth/v1/admin/users?email=${encodeURIComponent(ownerEmail)}`,
          { headers: { apikey: serviceRoleKey, Authorization: `Bearer ${serviceRoleKey}` } },
        );
        const searchData = await searchRes.json().catch(() => ({}));
        const existingUser = (searchData?.users || []).find(
          (u: { email: string }) => u.email?.toLowerCase() === ownerEmail,
        );

        if (!existingUser?.id) {
          throw new Error(`Failed to create owner auth user: ${authError.message}`);
        }

        await supabaseAdmin.auth.admin.updateUserById(existingUser.id, {
          password: ownerPassword,
          email_confirm: true,
          user_metadata: {
            organization_slug: slug,
            organization_id: organizationId,
            role: OWNER_ORG_ROLE,
            must_change_password: true,
            first_login_flow: "self_serve_owner",
          },
        });

        authUserId = existingUser.id;
      } else {
        if (!authData.user?.id) {
          throw new Error("Failed to create owner auth user: unknown error");
        }
        authUserId = authData.user.id;
        userWasCreated = true;
      }

      userId = authUserId;

      const { error: employeeError } = await supabaseAdmin
        .from("employees")
        .insert({
          user_id: userId,
          employee_id: generateEmployeeId(),
          full_name: ownerFullName,
          email: ownerEmail,
          phone: payload.owner_phone?.trim() || null,
          designation: payload.owner_designation?.trim() || DEFAULT_OWNER_DESIGNATION,
          department: payload.owner_department?.trim() || DEFAULT_OWNER_DEPARTMENT,
          organization_id: organizationId,
          lab_id: labId,
          is_active: true,
        });

      if (employeeError) {
        throw new Error(`Failed to create owner employee profile: ${employeeError.message}`);
      }

      employeeCreated = true;

      const { error: roleError } = await supabaseAdmin
        .from("user_roles")
        .upsert({ user_id: userId, role: "admin" }, { onConflict: "user_id,role" });

      if (roleError) {
        throw new Error(`Failed to assign owner role: ${roleError.message}`);
      }

      const { error: orgUserError } = await supabaseAdmin
        .from("organization_users")
        .insert({
          organization_id: organizationId,
          user_id: userId,
          role: OWNER_ORG_ROLE,
          is_primary: true,
          is_active: true,
        });

      if (orgUserError) {
        throw new Error(`Failed to create organization membership: ${orgUserError.message}`);
      }

      // Clear any stale primary flag on other lab_users for this user before inserting
      await supabaseAdmin
        .from("lab_users")
        .update({ is_primary: false })
        .eq("user_id", userId)
        .eq("is_primary", true);

      const { error: labUserError } = await supabaseAdmin
        .from("lab_users")
        .insert({
          user_id: userId,
          lab_id: labId,
          role: "admin",
          is_primary: true,
          organization_id: organizationId,
        });

      if (labUserError) {
        throw new Error(`Failed to create lab membership: ${labUserError.message}`);
      }

      return jsonResponse(
        {
          success: true,
          organization_id: organizationId,
          organization_slug: slug,
          lab_id: labId,
          lab_code: labCode,
          owner_user_id: userId,
          primary_domain: primaryDomain,
          access_domain: secondaryDomain || primaryDomain,
          secondary_domain: secondaryDomain,
        },
        200,
      );
    } catch (error) {
      await rollback();
      throw error;
    }
  } catch (error: unknown) {
    const message = error instanceof Error ? error.message : "Failed to provision organization";
    console.error("Error in provision-organization:", error);
    return jsonResponse({ error: message }, 500);
  }
});
